// Buat lookup maps
const skuMap = new Map();
const idMap = new Map();
const nameMap = new Map();

function normalizeName(str) {
  if (!str) return "";
  return String(str).toLowerCase().replace(/[^a-z0-9]/g, "");
}

function getTokens(str) {
  if (!str) return [];
  return String(str).toLowerCase().replace(/[^a-z0-9]/g, " ").split(/\s+/).filter(w => w.length > 1);
}

OFFICIAL_PRODUCT_CATALOG.forEach(item => {
  if (item.sku) {
    skuMap.set(item.sku.toUpperCase(), item);
  }
  if (item.id != null) {
    idMap.set(String(item.id), item);
  }
  const norm = normalizeName(item.title);
  if (norm) {
    nameMap.set(norm, item);
  }
});

// Registrasi aliases
Object.entries(SKU_ALIASES).forEach(([alias, target]) => {
  const targetItem = skuMap.get(target);
  if (targetItem) {
    skuMap.set(alias.toUpperCase(), targetItem);
  }
});

function findByTokens(rawName) {
  const queryTokens = getTokens(rawName);
  if (queryTokens.length < 2) return null;

  let bestMatch = null;
  let highestOverlapRatio = 0;

  for (const catItem of OFFICIAL_PRODUCT_CATALOG) {
    const catTokens = getTokens(catItem.title);
    const overlap = queryTokens.filter(t => catTokens.includes(t));
    const ratio = overlap.length / queryTokens.length;

    if (ratio >= 0.5 && overlap.length >= 2 && ratio > highestOverlapRatio) {
      highestOverlapRatio = ratio;
      bestMatch = catItem;
    }
  }

  return bestMatch;
}

/**
 * Menyelesaikan gambar studio resmi Habitic berdasarkan objek item, SKU, ID, atau nama
 * @param {Object|string} item
 * @param {Object} [options]
 * @param {boolean} [options.preferCdn=false] Jika true, kembalikan URL CDN Habitic
 * @returns {string|null} Path gambar lokal atau URL CDN
 */
export function resolveProductStudioImage(item, options = {}) {
  if (!item) return null;
  const preferCdn = Boolean(options && options.preferCdn);

  // Jika item berupa string (SKU atau ID langsung)
  if (typeof item === "string" || typeof item === "number") {
    const key = String(item).trim();
    const bySku = skuMap.get(key.toUpperCase());
    if (bySku) return preferCdn ? bySku.cdn : bySku.local;
    const byId = idMap.get(key);
    if (byId) return preferCdn ? byId.cdn : byId.local;
    return null;
  }

  // 1. Prioritas utama: pencarian berdasarkan SKU resmi Habitic
  const rawSku = (item.sku || "").trim().toUpperCase();
  if (rawSku && skuMap.has(rawSku)) {
    const match = skuMap.get(rawSku);
    return preferCdn ? match.cdn : match.local;
  }

  // 2. Prioritas kedua: pencarian berdasarkan ID numerik resmi Habitic (260-352)
  const rawId = item.id != null ? String(item.id).trim() : "";
  if (rawId && idMap.has(rawId)) {
    const match = idMap.get(rawId);
    return preferCdn ? match.cdn : match.local;
  }

  // Periksa apakah item memiliki custom external URL yang BUKAN dari Supabase storage
  const existingUrl = item.image_url || (Array.isArray(item.images) ? item.images[0] : null);
  const isSupabaseStorage = typeof existingUrl === "string" && (existingUrl.includes(".supabase.co/storage") || existingUrl.includes("/product-images/"));
  const isHabiticLocal = typeof existingUrl === "string" && existingUrl.includes("/assets/images/products/");

  // Jika item sudah memiliki custom image URL dari domain luar (dan bukan Supabase storage), jangan override dengan fuzzy name!
  if (existingUrl && !isSupabaseStorage && !isHabiticLocal) {
    return null;
  }

  // 3. Prioritas ketiga: pencarian berdasarkan kesamaan nama produk (hanya untuk produk tanpa foto atau foto lama storage)
  const rawName = item.name || item.title || "";
  if (rawName) {
    const norm = normalizeName(rawName);
    if (nameMap.has(norm)) {
      const match = nameMap.get(norm);
      return preferCdn ? match.cdn : match.local;
    }
    const tokenMatch = findByTokens(rawName);
    if (tokenMatch) {
      return preferCdn ? tokenMatch.cdn : tokenMatch.local;
    }
  }

  // 4. Jika gambar bawaan item sudah berupa path /assets/images/products/
  if (isHabiticLocal) {
    const filename = existingUrl.split("/").pop();
    return preferCdn ? (HABITIC_STUDIO_CDN_BASE + filename) : (HABITIC_STUDIO_LOCAL_BASE + filename);
  }

  return null;
}

/**
 * Menyelesaikan gambar studio beserta URL CDN fallback-nya
 * @param {Object|string} item
 * @returns {{ local: string, cdn: string, title: string, sku: string }|null}
 */
export function getProductStudioImageMeta(item) {
  if (!item) return null;
  let match = null;

  if (typeof item === "string" || typeof item === "number") {
    const key = String(item).trim();
    match = skuMap.get(key.toUpperCase()) || idMap.get(key);
  } else {
    const rawSku = (item.sku || "").trim().toUpperCase();
    if (rawSku && skuMap.has(rawSku)) {
      match = skuMap.get(rawSku);
    }
    if (!match && item.id != null) {
      match = idMap.get(String(item.id).trim());
    }
    if (!match) {
      const existingUrl = item.image_url || (Array.isArray(item.images) ? item.images[0] : null);
      const isSupabaseStorage = typeof existingUrl === "string" && (existingUrl.includes(".supabase.co/storage") || existingUrl.includes("/product-images/"));
      const isHabiticLocal = typeof existingUrl === "string" && existingUrl.includes("/assets/images/products/");
      
      if (!existingUrl || isSupabaseStorage || isHabiticLocal) {
        const rawName = item.name || item.title;
        if (rawName) {
          const norm = normalizeName(rawName);
          match = nameMap.get(norm) || findByTokens(rawName);
        }
      }
    }
  }

  if (match) {
    return {
      local: match.local,
      cdn: match.cdn,
      title: match.title,
      sku: match.sku
    };
  }

  return null;
}

